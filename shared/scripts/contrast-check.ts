/**
 * Measures every declared text and background pairing of both themes against WCAG 2.2 AA
 * and writes docs/contrast-report.md.
 *
 * Usage
 *   node shared/scripts/contrast-check.ts           writes the report, fails below AA
 *   node shared/scripts/contrast-check.ts --check   also fails if the committed report is stale
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { THEMES, type TokenFile, contrastRatio, loadTokens, semanticColour, toHex } from './tokens-lib.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SOURCE = join(ROOT, 'packages/design-tokens/tokens.json');
const REPORT = join(ROOT, 'docs/contrast-report.md');

export interface Row {
  theme: string;
  fg: string;
  bg: string;
  use: string;
  ratio: number;
  min: number;
  fgHex: string;
  bgHex: string;
}

export function measure(tokens: TokenFile): Row[] {
  const rows: Row[] = [];
  for (const theme of THEMES) {
    for (const pair of tokens.contrastPairs) {
      const fg = semanticColour(tokens, theme, pair.fg);
      const bg = semanticColour(tokens, theme, pair.bg);
      rows.push({
        theme,
        fg: pair.fg,
        bg: pair.bg,
        use: pair.use,
        ratio: contrastRatio(fg, bg),
        min: pair.min,
        fgHex: toHex(fg),
        bgHex: toHex(bg),
      });
    }
  }
  return rows;
}

export function report(rows: Row[]): string {
  const lines = [
    '# Contrast report',
    '',
    'Generated by `shared/scripts/contrast-check.ts` from `packages/design-tokens/tokens.json`. Do not edit by hand.',
    '',
    'WCAG 2.2 AA, 4.5 to 1 for text and 3 to 1 for non-text parts. Translucent colours are composited over their background first.',
    '',
    '| Theme | Foreground | Background | Use | Ratio | Minimum | Result |',
    '|---|---|---|---|---|---|---|',
  ];
  for (const r of rows) {
    const ok = r.ratio >= r.min ? 'pass' : '**FAIL**';
    lines.push(
      `| ${r.theme} | \`${r.fg}\` ${r.fgHex} | \`${r.bg}\` ${r.bgHex} | ${r.use} | ${r.ratio.toFixed(2)} | ${r.min} | ${ok} |`,
    );
  }
  lines.push('');
  return lines.join('\n');
}

function main(): void {
  const check = process.argv.includes('--check');
  const rows = measure(loadTokens(SOURCE));
  const content = report(rows);
  const failing = rows.filter((r) => r.ratio < r.min);
  for (const r of failing) {
    console.error(`${r.theme} ${r.fg} on ${r.bg} is ${r.ratio.toFixed(2)}, needs ${r.min}`);
  }
  if (check) {
    let current = '';
    try {
      current = readFileSync(REPORT, 'utf8');
    } catch {
      current = '';
    }
    if (current !== content) {
      console.error('docs/contrast-report.md is out of date, run npm run contrast');
      process.exit(1);
    }
  } else {
    writeFileSync(REPORT, content);
    console.log(`wrote docs/contrast-report.md, ${rows.length} pairs, ${failing.length} failing`);
  }
  if (failing.length > 0) {
    process.exit(1);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
