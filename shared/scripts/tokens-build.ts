/**
 * Generates the web CSS and the mobile Dart colours from packages/design-tokens/tokens.json.
 *
 * Usage
 *   node shared/scripts/tokens-build.ts           writes both files
 *   node shared/scripts/tokens-build.ts --check   fails if either file is out of date
 *
 * Both outputs are committed, so CI runs the check and a stale file fails the build.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  THEMES,
  type Hsl,
  type ThemeName,
  type TokenFile,
  loadTokens,
  num,
  scaleColour,
  semanticColour,
  semanticNames,
  semanticRef,
} from './tokens-lib.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SOURCE = join(ROOT, 'packages/design-tokens/tokens.json');
export const CSS_OUT = join(ROOT, 'packages/design-tokens/dist/tokens.css');
export const DART_OUT = join(ROOT, 'mobile/lib/core/theme/tokens.g.dart');

const HEADER = 'Generated by shared/scripts/tokens-build.ts from packages/design-tokens/tokens.json. Do not edit.';

function channels(c: Hsl): string {
  return `${num(c.h)} ${num(c.s)}% ${num(c.l)}%`;
}

function themeBlock(tokens: TokenFile, theme: ThemeName, indent: string): string[] {
  const lines = [`${indent}color-scheme: ${theme};`];
  for (const name of semanticNames(tokens)) {
    const ref = semanticRef(tokens, theme, name);
    const c = semanticColour(tokens, theme, name);
    // A plain step reference reuses the step's channels, so a palette change flows through.
    const value = ref ? `var(--${ref.replace('.', '-')})` : channels(c);
    lines.push(`${indent}--${name}-c: ${value};`);
    lines.push(
      c.a < 1
        ? `${indent}--${name}: hsl(var(--${name}-c) / ${num(c.a)});`
        : `${indent}--${name}: hsl(var(--${name}-c));`,
    );
  }
  return lines;
}

export function buildCss(tokens: TokenFile): string {
  const base = scaleColour(tokens, `${tokens.brandBase.scale}.${tokens.brandBase.step}`);
  const out = [`/* ${HEADER} */`, '', ':root {'];
  out.push(`  --brand-h: ${num(base.h)};`, `  --brand-s: ${num(base.s)}%;`, `  --brand-l: ${num(base.l)}%;`);
  for (const [scale, def] of Object.entries(tokens.scales)) {
    for (const step of Object.keys(def.steps)) {
      out.push(`  --${scale}-${step}: ${channels(scaleColour(tokens, `${scale}.${step}`))};`);
    }
  }
  out.push('}', '');
  // Dark is the default, so it also applies before theme-init.js has set the attribute.
  out.push(":root,", ":root[data-theme='dark'] {", ...themeBlock(tokens, 'dark', '  '), '}', '');
  out.push(":root[data-theme='light'] {", ...themeBlock(tokens, 'light', '  '), '}', '');
  out.push('@media (prefers-color-scheme: light) {', "  :root[data-theme='system'] {");
  out.push(...themeBlock(tokens, 'light', '    '), '  }', '}', '');
  return out.join('\n');
}

function camel(name: string): string {
  return name.replace(/-([a-z0-9])/g, (_, ch: string) => ch.toUpperCase());
}

function dartHsl(c: Hsl): string {
  return `HSLColor.fromAHSL(${num(c.a)}, ${num(c.h)}, ${num(c.s / 100)}, ${num(c.l / 100)})`;
}

export function buildDart(tokens: TokenFile): string {
  const names = semanticNames(tokens);
  const out = [
    `// ${HEADER}`,
    '',
    "import 'package:flutter/painting.dart';",
    '',
    '/// Every scale step as HSL, identical to the web custom properties.',
    'abstract final class R16aPalette {',
  ];
  for (const [scale, def] of Object.entries(tokens.scales)) {
    for (const step of Object.keys(def.steps)) {
      out.push(`  static const HSLColor ${scale}${step} = ${dartHsl(scaleColour(tokens, `${scale}.${step}`))};`);
    }
  }
  out.push('}', '');
  out.push('/// Semantic colours of one theme. Widgets use these through the app theme, never the palette.');
  out.push('final class R16aSemantic {');
  out.push('  const R16aSemantic({');
  for (const n of names) {
    out.push(`    required this.${camel(n)},`);
  }
  out.push('  });', '');
  for (const n of names) {
    out.push(`  final HSLColor ${camel(n)};`);
  }
  for (const theme of THEMES) {
    out.push('', `  static const ${theme} = R16aSemantic(`);
    for (const n of names) {
      out.push(`    ${camel(n)}: ${dartHsl(semanticColour(tokens, theme, n))},`);
    }
    out.push('  );');
  }
  out.push('}', '');
  return out.join('\n');
}

function main(): void {
  const check = process.argv.includes('--check');
  const tokens = loadTokens(SOURCE);
  const outputs: [string, string][] = [
    [CSS_OUT, buildCss(tokens)],
    [DART_OUT, buildDart(tokens)],
  ];
  let stale = false;
  for (const [path, content] of outputs) {
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      current = '';
    }
    if (current === content) {
      continue;
    }
    if (check) {
      console.error(`out of date, run npm run tokens:build (${path.replace(ROOT + '/', '')})`);
      stale = true;
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
      console.log(`wrote ${path.replace(ROOT + '/', '')}`);
    }
  }
  if (stale) {
    process.exit(1);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
